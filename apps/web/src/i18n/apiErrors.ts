/** ارقام ASCII → عربی-هندی (٠١٢٣) — همانlocale ar-EG فرمترها */
function arDigits(n: number | string): string {
        const AR = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩']
        return String(n).replace(/\d/g, (d) => AR[Number(d)])
}

