/** الگوهای دارای جای‌گذاری — نام محصول در متن فارسی سرور می‌آید */
const PATTERNS_AR: { re: RegExp; build: (m: RegExpExecArray) => string }[] = [
	{
		// سایز انتخابی «برگر ذغالی» دیگر موجود نیست — سبد خرید را به‌روز کنید.
		re: /^سایز انتخابی «(.+)» دیگر موجود نیست/,
		build: (m) =>
			`الحجم المختار لـ«${m[1]}» لم يعد متوفراً — حدِّث سلة الشراء.`,
	},
]

/**
 * رارد ۳۳ — حل خطای API به عربی.
 * ورودی: کد و پیامِ خطای پرتاب‌شده از handleResponse (پیام = فارسی سرور).
 * خروجی: پیام عربی اگر نقشه شد؛ «همان فارسی» اگر نشد (تصمیم کاربر).
 */
export function arApiErrorMessage(
	code: string | undefined,
	message: string,
): string {
	// ۱) تطبیق دقیق پیام — مسیرهای مشتری
	const exact = MESSAGES_AR[message]
	if (exact) return exact

	// ۲) الگوهای دارای جای‌گذاری (نام محصول و…)
	for (const p of PATTERNS_AR) {
		const m = p.re.exec(message)
		if (m) return p.build(m)
	}

	// ۳) DEVICE_LIMIT_REACHED — عددِ «حداکثر N دستگاه» داخل پیام فارسی است
	if (code === 'DEVICE_LIMIT_REACHED') {
		const m = /حداکثر\s+(\d+)/.exec(message)
		if (m)
			return `الحد الأقصى ${arDigits(m[1])} أجهزة. لإضافة جهاز جديد، احذف أحد الأجهزة السابقة.`
		return 'تم بلوغ الحد الأقصى للأجهزة. لإضافة جهاز جديد، احذف أحد الأجهزة السابقة.'
	}

	// ۴) کد عمومی — ۹ کد باقی
	const byCode = code ? CODES_AR[code] : undefined
	if (byCode) return byCode

	// ۵) «خطای N» — handleResponse وقتی body خطا ندارد
	const st = /^خطای\s+(\d+)$/.exec(message)
	if (st) return `خطأ ${arDigits(st[1])}`

	// ۶) نقشه‌نشده = فارسی (تصمیم کاربر)
	return message
}
