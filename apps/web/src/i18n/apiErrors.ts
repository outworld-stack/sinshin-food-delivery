// نکته‌ی معماری: این ترجمه «مصرف‌کننده» انجام می‌دهد (useI18n().apiError در
// توست‌های داشبورد) نه handleResponse — چون admin/admin2/courier هم از همان
// fetch helper استفاده می‌کنند و طبق تصمیم کاربر باید فارسیِ خالص بمانند.

/** ارقام ASCII → عربی-هندی (٠١٢٣) — همانlocale ar-EG فرمترها */
function arDigits(n: number | string): string {
	const AR = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩']
	return String(n).replace(/\d/g, (d) => AR[Number(d)])
}

