// پاک‌سازی و اعتبارسنجی شماره‌ی موبایل ایران — منبع واحد رارد ۴۸ (اسکن B7).
// پیش از این، همین دو خط در ۸+ نقطه (مودال‌های ادمین، ورود مشتری/پیک،
// گزارش‌ها، ویرایش کاربر) تکرار می‌شد و متن خطای دو مودال هم دریفت کرده بود.

/** فقط ارقام را نگه می‌دارد (حذف هر نویسه‌ی غیرعددی هنگام تایپ) */
export const sanitizePhone = (v: string) => v.replace(/[^0-9]/g, '')

/** آیا شکل شماره‌ی موبایل ایران (صفر-نه و نه رقم بعدی) معتبر است؟ */
export const isValidIranPhone = (v: string) => /^09[0-9]{9}$/.test(v)